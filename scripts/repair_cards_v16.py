def main():
    with open(INPUT, 'r', encoding='utf-8') as f:
        cards = json.load(f)
    print(f"加载v1.5卡片: {len(cards)}张")
    tf = df = dnf = 0
    for card in cards:
        cid = card['卡片ID']
        if cid in TITLE_FIXES:
            card['标题'] = TITLE_FIXES[cid]; card['_v1.6修复'] = '标题修复'; tf += 1
        if cid in DOS_FIXES:
            action = card.get('行动建议', {}) or {}
            action['做什么'] = DOS_FIXES[cid]; card['行动建议'] = action; df += 1
        if cid in DONT_FIXES:
            action = card.get('行动建议', {}) or {}
            old = action.get('不做什么', [])
            if isinstance(old, list) and (not old or all(str(d).strip() in ['待补充',''] for d in old)):
                action['不做什么'] = DONT_FIXES[cid]; card['行动建议'] = action; dnf += 1
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"标题修复:{tf} 做什么修复:{df} 不做什么修复:{dnf}")
    print(f"已保存v1.6: {OUTPUT} ({os.path.getsize(OUTPUT)}字节)")

if __name__ == '__main__': main()
